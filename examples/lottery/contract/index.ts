// This file's main purpose is to export the compiled contract. The imports below
// resolve against contract/managed/lottery, which is generated by `npm run compile`
// (gitignored). Write contract/lottery.compact first, then compile.
import { CompiledContract } from '@midnight-ntwrk/midnight-js-protocol/compact-js';
import path from 'node:path';

export {
  Contract,
  ledger,
  pureCircuits,
  type Witnesses,
  type Ledger,
  type ImpureCircuits,
  type PureCircuits,
} from './managed/lottery/contract/index.js';
import { Contract } from './managed/lottery/contract/index.js';
import { witnesses } from './witnesses.js';
const currentDir = path.resolve(new URL(import.meta.url).pathname, '..');
export const zkConfigPath = path.resolve(currentDir, 'managed', 'lottery');

export const CompiledLotteryContract = CompiledContract.make(
  'LotteryContract',
  Contract,
).pipe(
  CompiledContract.withWitnesses(witnesses),
  CompiledContract.withCompiledFileAssets(zkConfigPath),
);

